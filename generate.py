#!/usr/bin/env python3
"""Write each harness's agent files from agents/*.md and factory.yaml.

Usage: ./generate.py           write the files
       ./generate.py --check   fail if any generated file is out of date
Needs PyYAML (pip install pyyaml).
"""
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent


def claude_code(name, agent, prompt, target):
    lines = ["---", f"name: {name}", f"description: {agent['description']}"]
    if agent["tools"] != "all":
        tools = [t for cap in agent["tools"] for t in target["tools"][cap]]
        lines.append(f"tools: {', '.join(tools)}")
    lines += [f"model: {target['models'][agent['model']]}", "---"]
    return {f".claude/agents/{name}.md": "\n".join(lines) + "\n" + prompt}


def codex(agents, prompts, target):
    out = [
        "# Agent roles",
        "",
        "Generated by agent-factory's generate.py. When asked to act as one of these roles, follow its instructions.",
    ]
    for name, agent in agents.items():
        sandbox = "workspace-write" if agent["tools"] == "all" or "edit" in agent["tools"] else "read-only"
        out += ["", f"## {name}", "", agent["description"], "", f"Sandbox: {sandbox}."]
        model = target.get("models", {}).get(agent["model"])
        if model:
            out.append(f"Model: {model}.")
        out += ["", prompts[name].rstrip("\n")]
    return {"codex/AGENTS.md": "\n".join(out) + "\n"}


def render():
    factory = yaml.safe_load((ROOT / "factory.yaml").read_text())
    agents, targets = factory["agents"], factory["targets"]
    prompts = {name: (ROOT / "agents" / f"{name}.md").read_text() for name in agents}
    files = {}
    for name, agent in agents.items():
        files.update(claude_code(name, agent, prompts[name], targets["claude-code"]))
    files.update(codex(agents, prompts, targets["codex"]))
    return files


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, text in render().items():
        path = ROOT / rel
        if path.exists() and path.read_text() == text:
            continue
        stale.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check and stale:
        sys.exit("Out of date, run ./generate.py: " + ", ".join(stale))
    print(("Out of date: " if check else "Wrote: ") + (", ".join(stale) or "nothing"))


if __name__ == "__main__":
    main()
